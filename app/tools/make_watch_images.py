"""Generate placeholder specimen images for the StopWatch and write them as a C header.

Usage (from the repo root):
    python app/tools/make_watch_images.py

Output:
    app/watch/console/specimens.h   (JPEG bytes as const arrays in flash)
    app/tools/out/*.jpg             (the same images for viewing)

These are synthetic drawings, not real photos. To use real photos, drop 180x135 JPEGs
named healthy.jpg, coccidiosis.jpg, salmonella.jpg and ncd.jpg into app/tools/real/
and rerun. Files in real/ take priority.
"""
import io
import math
import os
import random

from PIL import Image, ImageDraw, ImageFilter

W, H = 180, 135
HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "out")
REAL_DIR = os.path.join(HERE, "real")
HEADER = os.path.join(HERE, "..", "watch", "console", "specimens.h")

TYPES = {
    "healthy": (122, 74, 34),
    "coccidiosis": (74, 36, 24),
    "salmonella": (201, 178, 74),
    "ncd": (79, 174, 74),
}


def litter(rnd):
    img = Image.new("RGB", (W, H), (27, 23, 18))
    d = ImageDraw.Draw(img, "RGBA")
    for _ in range(260):
        x, y = rnd.random() * W, rnd.random() * H
        a, ln = rnd.random() * 6.28, 4 + rnd.random() * 9
        col = (150 + int(rnd.random() * 70), 120 + int(rnd.random() * 50), 70 + int(rnd.random() * 40), 60 + int(rnd.random() * 60))
        d.line([x, y, x + math.cos(a) * ln, y + math.sin(a) * ln], fill=col, width=1)
    return img


def draw(kind, seed):
    rnd = random.Random(seed)
    img = litter(rnd)
    base = TYPES[kind]
    d = ImageDraw.Draw(img, "RGBA")
    cx, cy = W // 2, H // 2 + 4
    wet = 1.0 if kind == "healthy" else 1.4
    rx, ry = int(34 * wet), int(25 * wet)
    d.ellipse([cx - rx, cy - ry, cx + rx, cy + ry], fill=base + (255,))
    dark = tuple(max(0, c - 18) for c in base)
    d.ellipse([cx - rx + 8, cy - ry + 9, cx + rx - 12, cy + ry - 6], fill=dark + (255,))
    if kind == "healthy":
        d.ellipse([cx + 4, cy - 17, cx + 28, cy - 2], fill=(239, 233, 222, 255))
    elif kind == "coccidiosis":
        for i in range(5):
            x0 = cx - 24 + i * 11
            d.line([x0, cy - 12, x0 + 5, cy + 2, x0 - 2, cy + 16], fill=(163, 35, 28, 255), width=2)
    elif kind == "salmonella":
        for _ in range(14):
            x, y, r = cx + rnd.uniform(-rx, rx) * 0.8, cy + rnd.uniform(-ry, ry) * 0.8, rnd.uniform(1.5, 3.5)
            d.ellipse([x - r, y - r, x + r, y + r], fill=(255, 248, 210, 140))
    elif kind == "ncd":
        d.ellipse([cx - rx + 6, cy - ry + 6, cx + rx - 14, cy + ry - 10], fill=(190, 255, 150, 70))
    return img.filter(ImageFilter.GaussianBlur(0.6))


def to_jpeg(img):
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=72, optimize=True)
    return buf.getvalue()


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    parts = ["// Generated by app/tools/make_watch_images.py. Do not edit by hand.\n#pragma once\n#include <stdint.h>\n\n"]
    for i, kind in enumerate(TYPES):
        real = os.path.join(REAL_DIR, kind + ".jpg")
        if os.path.exists(real):
            img = Image.open(real).convert("RGB").resize((W, H))
            src = "real"
        else:
            img = draw(kind, 100 + i)
            src = "synthetic"
        data = to_jpeg(img)
        img.save(os.path.join(OUT_DIR, kind + ".jpg"), quality=72)
        body = ",".join(str(b) for b in data)
        parts.append(f"// {kind} ({src}), {len(data)} bytes\nstatic const uint8_t IMG_{kind.upper()}[] = {{{body}}};\nstatic const uint32_t IMG_{kind.upper()}_LEN = {len(data)};\n\n")
        print(f"{kind}: {len(data)} bytes ({src})")
    with open(HEADER, "w", newline="\n") as f:
        f.write("".join(parts))
    print("wrote", os.path.normpath(HEADER))


if __name__ == "__main__":
    main()
